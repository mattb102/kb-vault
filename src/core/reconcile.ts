/**
 * Nightly vault reconcile.
 *
 * Reads the last N days of scratchpad observations, asks Claude which canonical
 * files they affect (triage), then for each file proposes a full rewrite that
 * is applied only when it passes mechanical guards. Every applied change —
 * including its diff — lands in AI-Observations/reconcile/<date>.md so the
 * morning report can surface "changed X: Y" and a revert is one git command.
 *
 * Requires the claude CLI on PATH with subscription auth.
 * Disabled by default (reconcile.enabled: false in config).
 */
import { readFile, writeFile, mkdir, readdir, stat } from "fs/promises";
import { join, relative } from "path";
import { execFile } from "child_process";
import { promisify } from "util";
import matter from "gray-matter";
import { config } from "./config.js";
import { readScratchpad, readScratchpadEntries, renderEntry, type Entry } from "./scratchpad.js";
import { claudePrompt, CLAUDE_MODEL } from "./claude-cli.js";
import { today } from "./utils.js";
import { sweepOverdueNudges, type NudgeSweepResult } from "./nudge-sweep.js";

const execFileP = promisify(execFile);

export const RECONCILE_DIR_REL = "AI-Observations/reconcile";

// Default routing manifest path. Override with reconcile.routingFile in config.
const DEFAULT_ROUTING_REL = "Core/routing.md";

/** Paths the reconciler must never write, expressed as regexes on vault-relative paths. */
const BASE_NEVER_TOUCH: RegExp[] = [
  /^AI-Observations\//,
  /^Reports\//,
  /^_templates\//,
  /^Core\/core-identity\.md$/,
  /^Core\/routing\.md$/,
  /^CLAUDE\.md$/,
  /^Media\/steam-library\.md$/i, // auto-generated by sync-steam; reconcile uses mediaSweep for Games/
];

const MAX_FILE_BYTES = 24_000;
const MAX_FILES_PER_RUN = 8;

export interface TriageItem {
  file: string;
  reason: string;
  facts: string[];
}

export interface FileResult {
  file: string;
  status: "applied" | "no-change" | "skipped" | "rejected" | "error";
  reason: string;
  facts: string[];
  diff?: string;
}

export interface ReconcileResult {
  date: string;
  days: number;
  entries: number;
  triage: TriageItem[];
  results: FileResult[];
  nudgeSweep?: NudgeSweepResult;
  logPath?: string;
}

export interface ReconcileOptions {
  days?: number;
  dryRun?: boolean;
  only?: string;
  max?: number;
  model?: string;
}

export function isNeverTouch(rel: string): boolean {
  if (BASE_NEVER_TOUCH.some((re) => re.test(rel))) return true;
  // Protect the configured standing-rules and instructions files from overwrites.
  const standingRules = config.standingRulesFile || "Core/standing-rules.md";
  if (rel === standingRules) return true;
  return false;
}

async function listCanonicalFiles(): Promise<string[]> {
  const out: string[] = [];
  async function walk(dir: string) {
    for (const e of await readdir(dir, { withFileTypes: true })) {
      if (e.name.startsWith(".")) continue;
      const full = join(dir, e.name);
      if (e.isDirectory()) await walk(full);
      else if (e.name.endsWith(".md")) {
        const rel = relative(config.vaultPath, full);
        if (!isNeverTouch(rel)) out.push(rel);
      }
    }
  }
  await walk(config.vaultPath);
  return out.sort();
}

function recentEntries(entries: Entry[], days: number): Entry[] {
  const cutoff = new Date(Date.now() - days * 86_400_000);
  return entries.filter((e) => e.date >= cutoff);
}

/** Pull the first JSON array/object out of a model reply that may be fenced or chatty. */
export function extractJson<T>(text: string): T {
  const fenced = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  const candidate = fenced ? fenced[1] : text;
  const start = candidate.search(/[\[{]/);
  if (start === -1) throw new Error("no JSON in reply");
  return JSON.parse(candidate.slice(start).trim()) as T;
}

/**
 * Mechanical guards between "Claude proposed this" and "we wrote it".
 * Returns the content to write (with `updated:` stamped) or a rejection reason.
 */
export function applyGuards(
  oldRaw: string,
  proposed: string,
  date: string,
): { ok: true; content: string } | { ok: false; reason: string } {
  const p = proposed.trim();
  if (!p || /^NO[ _-]?CHANGE\b/i.test(p)) return { ok: false, reason: "no change" };
  if (!p.startsWith("---\n")) return { ok: false, reason: "proposal lost frontmatter" };
  let parsed: matter.GrayMatterFile<string>;
  try {
    parsed = matter(p);
  } catch (e) {
    return {
      ok: false,
      reason: `frontmatter unparseable: ${(e as Error).message}`,
    };
  }
  const oldParsed = matter(oldRaw);
  if ((oldParsed.data.type ?? null) !== (parsed.data.type ?? null)) {
    return { ok: false, reason: "proposal changed frontmatter type" };
  }
  const ratio = p.length / Math.max(oldRaw.length, 1);
  if (ratio < 0.6)
    return { ok: false, reason: `proposal shrank file to ${Math.round(ratio * 100)}%` };
  if (ratio > 2.5)
    return { ok: false, reason: `proposal grew file to ${Math.round(ratio * 100)}%` };
  if (
    /```/.test(oldRaw) &&
    oldRaw.match(/```/g)!.length !== (p.match(/```/g) ?? []).length
  ) {
    return { ok: false, reason: "code-fence count changed" };
  }
  if (p.replace(/\s+/g, " ") === oldRaw.trim().replace(/\s+/g, " ")) {
    return { ok: false, reason: "no change" };
  }
  const stamped = matter.stringify(parsed.content, { ...parsed.data, updated: date });
  return { ok: true, content: stamped };
}

function triagePrompt(
  observations: string,
  routing: string,
  files: string[],
  days: number,
  owner: string,
): string {
  const routingSection = routing
    ? `=== ROUTING MANIFEST ===\n${routing}\n\n`
    : "(no routing manifest — use the file list to infer where each fact belongs)\n\n";
  return `You are the nightly reconciler for ${owner}'s Obsidian vault. Below are the last ${days} day(s) of AI observations logged during conversations, the vault's routing manifest (which file each kind of fact belongs in), and the list of canonical files that may be edited.

Your job in this step is TRIAGE ONLY: decide which canonical files contain facts that the observations show to be stale, wrong, or missing. Be conservative. A file qualifies only if an observation states a concrete fact (a status changed, a thing happened, a number moved, a plan died) that the file's purpose covers. Mood, speculation, and AI meta-observations do not qualify.

Return ONLY a JSON array, at most ${MAX_FILES_PER_RUN} items, most important first:
[{"file": "<exact path from the list>", "reason": "<one line>", "facts": ["<concrete fact to write, with its date>", ...]}]
Return [] if nothing qualifies.

${routingSection}=== CANONICAL FILES ===
${files.join("\n")}

=== OBSERVATIONS (last ${days} day(s)) ===
${observations}`;
}

function rewritePrompt(
  rel: string,
  content: string,
  item: TriageItem,
  observations: string,
  owner: string,
): string {
  return `You are updating one canonical file in ${owner}'s Obsidian vault so it reflects facts from recent observations. Today is ${today()}.

FILE: ${rel}
WHY IT WAS SELECTED: ${item.reason}
FACTS TO REFLECT:
${item.facts.map((f) => `- ${f}`).join("\n")}

Rules:
- Return the COMPLETE new file, frontmatter included, and nothing else. If after reading you conclude nothing should change, return exactly: NO CHANGE
- Keep the file's structure, headers, voice (terse, dated, factual) and every fact that is still true. Edit the specific lines the facts touch; do not rewrite unrelated sections. Do not add commentary about this process.
- Prefer a dated line ("${today()}: ...") over rewriting history. Never delete a section; never change the frontmatter \`type\`; leave \`updated:\` alone (it is stamped automatically).
- If a fact contradicts the file and you cannot tell which is right, do not guess — leave the line and add "(conflicting report <date>; unresolved)".

=== CURRENT FILE ===
${content}

=== OBSERVATIONS FOR CONTEXT ===
${observations}`;
}

// ─── book sweep ────────────────────────────────────────────────────────────────
//
// Backstop for reading reactions that only reached the scratchpad. Matches book
// observations to Media/Books/<slug>.md and appends any reactions the file
// doesn't already have. Append-only -- existing text is never rewritten.

const BOOKS_DIR_REL = "Media/Books";
const BOOK_SUBJECT_RE = /\b(reading|books?|audiobook|novel)\b/i;
const MAX_BOOK_FILES = 4;
const MAX_REACTIONS = 8;

interface BookFile {
  rel: string;
  title: string;
  keys: string[];
  status: string;
  raw: string;
}

/** Lowercase match keys: the title (sans leading "the"), plus its longest word if >= 6 chars. */
export function bookKeys(title: string): string[] {
  const t = title.toLowerCase().replace(/^the\s+/, "").trim();
  const longest = t
    .split(/[^a-z0-9']+/)
    .filter((w) => w.length >= 6)
    .sort((a, b) => b.length - a.length)[0];
  return [...new Set([t, ...(longest ? [longest] : [])])];
}

async function loadBookFiles(): Promise<BookFile[]> {
  let names: string[];
  try {
    names = await readdir(join(config.vaultPath, BOOKS_DIR_REL));
  } catch {
    return [];
  }
  const out: BookFile[] = [];
  for (const n of names.filter((x) => x.endsWith(".md") && x !== "README.md").sort()) {
    const rel = `${BOOKS_DIR_REL}/${n}`;
    const raw = await readFile(join(config.vaultPath, rel), "utf-8");
    const parsed = matter(raw);
    const h1 = parsed.content.match(/^# (.+)$/m)?.[1] ?? n.replace(/\.md$/, "").replace(/-/g, " ");
    const title = h1.split(/\s+[-—–]\s+/)[0].trim();
    out.push({ rel, title, keys: bookKeys(title), status: String(parsed.data.status ?? ""), raw });
  }
  return out;
}

/** Book observations grouped by file. */
export function matchBookEntries(entries: Entry[], books: Pick<BookFile, "rel" | "keys" | "status">[]) {
  const byFile = new Map<string, Entry[]>();
  const add = (rel: string, e: Entry) => byFile.set(rel, [...(byFile.get(rel) ?? []), e]);
  for (const e of entries) {
    if (e.type === "meta") continue;
    const text = `${e.subject}\n${e.body}`.toLowerCase();
    const hits = books.filter((b) => b.keys.some((k) => text.includes(k)));
    if (hits.length) hits.forEach((b) => add(b.rel, e));
    else if (BOOK_SUBJECT_RE.test(e.subject))
      books.filter((b) => b.status === "reading").forEach((b) => add(b.rel, e));
  }
  return byFile;
}

/** Append reactions as dated bullets under the configured section, deduping. */
export function appendReactions(raw: string, reactions: string[], date: string): string | null {
  const section = config.reconcileConfig.bookTakeSection;
  const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  const have = norm(raw);
  const fresh = reactions
    .map((r) => r.replace(/^\s*[-*]\s*/, "").trim())
    .filter((r) => r && !have.includes(norm(r)));
  if (!fresh.length) return null;
  const parsed = matter(raw);
  let body = parsed.content.replace(/\s+$/, "");
  const bullets = fresh.map((r) => `- ${date}: ${r}`).join("\n");
  if (body.includes(section)) {
    const sectionStart = body.indexOf(section);
    const afterSection = body.indexOf("\n## ", sectionStart + 1);
    const insertAt = afterSection === -1 ? body.length : afterSection;
    const before = body.slice(0, insertAt).replace(/\n+$/, "");
    const after = body.slice(insertAt);
    body = `${before}\n${bullets}\n${after}`;
  } else {
    body += `\n\n${section}\n${bullets}\n`;
  }
  return matter.stringify(body, { ...parsed.data, updated: date });
}

/** Append verbatim quotes under the configured saved-lines section, deduping. */
export function appendSavedLines(raw: string, lines: string[], date: string): string | null {
  const section = config.reconcileConfig.bookSavedLinesSection;
  const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  const have = norm(raw);
  const fresh = lines
    .map((l) => l.replace(/^\s*[-*]\s*/, "").trim())
    .filter((l) => l && !have.includes(norm(l)));
  if (!fresh.length) return null;
  const parsed = matter(raw);
  let body = parsed.content.replace(/\s+$/, "");
  const bullets = fresh.map((l) => `- ${date}: ${l}`).join("\n");
  if (body.includes(section)) {
    const sectionStart = body.indexOf(section);
    const afterSection = body.indexOf("\n## ", sectionStart + 1);
    const insertAt = afterSection === -1 ? body.length : afterSection;
    const before = body.slice(0, insertAt).replace(/\n+$/, "");
    const after = body.slice(insertAt);
    body = `${before}\n${bullets}\n${after}`;
  } else {
    body += `\n\n${section}\n${bullets}\n`;
  }
  return matter.stringify(body, { ...parsed.data, updated: date });
}

function bookSweepPrompt(book: BookFile, observations: string): string {
  return `You are filing the user's reactions to a book into its vault file. Below are the book file and recent AI observations from conversations with the user that mention this book or their current reading.

Return ONLY a JSON object: { "reactions": [...], "saved_lines": [...] }
- "reactions": the user's own opinions, feelings, impressions, questions about this book. Use their exact words in quotes; otherwise a tight paraphrase. One string per reaction, no leading dash and no leading date (the date will be prepended automatically). Terse, matching the file's voice. Lead with chapter/progress if the observation gives it (e.g. "ch. 12: ..."). At most ${MAX_REACTIONS} items. Return [] if none.
- "saved_lines": verbatim quotes FROM THE BOOK TEXT that the user mentioned saving or highlighted. Keep them verbatim/quoted. At most 4 items. Return [] if none.

Never include AI analysis, interpretations, connections, or observations about behavior or mood.
Skip logistics (start date, format, narrator, audiobook quality) and anything about a different book. When unsure, leave it out.

=== BOOK FILE (${book.rel}) ===
${book.raw}

=== OBSERVATIONS ===
${observations}`;
}

export async function bookSweep(entries: Entry[], date: string, model: string, dryRun: boolean): Promise<FileResult[]> {
  const books = await loadBookFiles();
  const byFile = matchBookEntries(entries, books);
  const results: FileResult[] = [];
  for (const book of books.filter((b) => byFile.has(b.rel)).slice(0, MAX_BOOK_FILES)) {
    const raw = await readFile(join(config.vaultPath, book.rel), "utf-8");
    const fr: FileResult = { file: book.rel, status: "no-change", reason: "book sweep: nothing new", facts: [] };
    results.push(fr);
    try {
      const obs = byFile.get(book.rel)!.map(renderEntry).join("\n\n");
      const reply = await claudePrompt(bookSweepPrompt({ ...book, raw }, obs), model, 240_000);
      const parsed = extractJson<{ reactions?: unknown[]; saved_lines?: unknown[] }>(reply);
      const reactions = (parsed.reactions ?? []).filter((r): r is string => typeof r === "string");
      const savedLines = (parsed.saved_lines ?? []).filter((l): l is string => typeof l === "string");
      let current = raw;
      let changed = false;
      const r1 = appendReactions(current, reactions.slice(0, MAX_REACTIONS), date);
      if (r1) { current = r1; changed = true; }
      const r2 = appendSavedLines(current, savedLines, date);
      if (r2) { current = r2; changed = true; }
      if (!changed) continue;
      fr.facts = [...reactions, ...savedLines];
      fr.diff = await unifiedDiff(raw, current, book.rel);
      fr.status = "applied";
      fr.reason = dryRun ? "book sweep -- dry run, not written" : `book sweep: filed reactions to ${book.title}`;
      if (!dryRun) await writeFile(join(config.vaultPath, book.rel), current);
    } catch (e) {
      fr.status = "error";
      fr.reason = `book sweep: ${(e as Error).message}`;
    }
  }
  return results;
}

// ─── media sweep ─────────────────────────────────────────────────────────────
//
// Like bookSweep but covers TV/Movies/VNs/Games per-item files. Append-only.

const MEDIA_DIRS: Array<{ dir: string; type: string; label: string }> = [
  { dir: "Media/TV", type: "tv", label: "TV show" },
  { dir: "Media/Movies", type: "movie", label: "film" },
  { dir: "Media/VNs", type: "vn", label: "visual novel" },
  { dir: "Media/Games", type: "game", label: "video game" },
];

interface MediaFile {
  rel: string;
  title: string;
  type: string;
  keys: string[];
  status: string;
  raw: string;
}

async function loadMediaFiles(): Promise<MediaFile[]> {
  const out: MediaFile[] = [];
  for (const { dir, type } of MEDIA_DIRS) {
    let names: string[];
    try {
      names = await readdir(join(config.vaultPath, dir));
    } catch {
      continue;
    }
    for (const n of names.filter((x) => x.endsWith(".md") && x !== "README.md").sort()) {
      const rel = `${dir}/${n}`;
      const raw = await readFile(join(config.vaultPath, rel), "utf-8");
      const parsed = matter(raw);
      if (parsed.data.type !== type) continue;
      const title: string = parsed.data.title ?? n.replace(/\.md$/, "").replace(/-/g, " ");
      out.push({ rel, title, type, keys: bookKeys(title), status: String(parsed.data.status ?? ""), raw });
    }
  }
  return out;
}

function mediaSweepPrompt(file: MediaFile, label: string, observations: string): string {
  return `You are filing the user's reactions to a ${label} into its vault file. Below are the file and recent AI observations from conversations with the user that mention this ${label}.

Return ONLY a JSON object: { "reactions": [...] }
- "reactions": the user's own opinions, feelings, impressions, questions about this ${label}. Use their exact words in quotes; otherwise a tight paraphrase. One string per reaction, no leading dash and no leading date (the date will be prepended automatically). Terse, matching the file's voice. At most ${MAX_REACTIONS} items. Return [] if none.

Never include AI analysis, interpretations, connections, or observations about behavior or mood.
Skip logistics (start date, episode counts) and anything about a different title. When unsure, leave it out.

=== FILE (${file.rel}) ===
${file.raw}

=== OBSERVATIONS ===
${observations}`;
}

export async function mediaSweep(entries: Entry[], date: string, model: string, dryRun: boolean): Promise<FileResult[]> {
  const files = await loadMediaFiles();
  const byFile = matchBookEntries(entries, files);
  const results: FileResult[] = [];
  const dirLabel = new Map<string, string>([
    ["Media/TV", "TV show"], ["Media/Movies", "film"], ["Media/VNs", "visual novel"], ["Media/Games", "video game"],
  ]);
  for (const file of files.filter((f) => byFile.has(f.rel)).slice(0, MAX_BOOK_FILES)) {
    const raw = await readFile(join(config.vaultPath, file.rel), "utf-8");
    const fr: FileResult = { file: file.rel, status: "no-change", reason: "media sweep: nothing new", facts: [] };
    results.push(fr);
    const dir = file.rel.split("/").slice(0, 2).join("/");
    const label = dirLabel.get(dir) ?? "media";
    try {
      const obs = byFile.get(file.rel)!.map(renderEntry).join("\n\n");
      const reply = await claudePrompt(mediaSweepPrompt({ ...file, raw }, label, obs), model, 240_000);
      const parsed = extractJson<{ reactions?: unknown[] }>(reply);
      const reactions = (parsed.reactions ?? []).filter((r): r is string => typeof r === "string");
      const r1 = appendReactions(raw, reactions.slice(0, MAX_REACTIONS), date);
      if (!r1) continue;
      fr.facts = reactions;
      fr.diff = await unifiedDiff(raw, r1, file.rel);
      fr.status = "applied";
      fr.reason = dryRun ? "media sweep -- dry run, not written" : `media sweep: filed reactions to ${file.title}`;
      if (!dryRun) await writeFile(join(config.vaultPath, file.rel), r1);
    } catch (e) {
      fr.status = "error";
      fr.reason = `media sweep: ${(e as Error).message}`;
    }
  }
  return results;
}

export async function reconcileVault(
  opts: ReconcileOptions = {},
): Promise<ReconcileResult> {
  const days = opts.days ?? 1;
  const date = today();
  const model = opts.model ?? CLAUDE_MODEL;
  const max = opts.max ?? MAX_FILES_PER_RUN;
  const owner = config.ownerName;
  const routingRel =
    (config as any).reconcileConfig?.routingFile ?? DEFAULT_ROUTING_REL;

  // Use readScratchpadEntries to include any archive months the window touches.
  const entries = await readScratchpadEntries({ sinceDays: days });
  const recent = recentEntries(entries, days);
  const result: ReconcileResult = {
    date,
    days,
    entries: recent.length,
    triage: [],
    results: [],
  };
  if (recent.length === 0) return result;

  const observations = recent.map(renderEntry).join("\n\n");

  let routing = "";
  try {
    routing = matter(
      await readFile(join(config.vaultPath, routingRel), "utf-8"),
    ).content;
  } catch {
    // Missing routing manifest is fine — the triage prompt adapts.
  }

  const files = await listCanonicalFiles();

  let triage: TriageItem[];
  if (opts.only) {
    triage = [{ file: opts.only, reason: "--only", facts: ["(see observations)"] }];
  } else {
    const reply = await claudePrompt(
      triagePrompt(observations, routing, files, days, owner),
      model,
      240_000,
    );
    triage = extractJson<TriageItem[]>(reply)
      .filter((t) => t && typeof t.file === "string")
      .slice(0, max);
  }
  result.triage = triage;

  for (const item of triage) {
    const rel = item.file.replace(/^\/+/, "");
    const abs = join(config.vaultPath, rel);
    const fr: FileResult = {
      file: rel,
      status: "skipped",
      reason: "",
      facts: item.facts ?? [],
    };
    result.results.push(fr);

    if (!files.includes(rel)) {
      fr.reason = "not a canonical file (or never-touch)";
      continue;
    }
    let size = 0;
    try {
      size = (await stat(abs)).size;
    } catch {
      fr.reason = "file missing";
      continue;
    }
    if (size > MAX_FILE_BYTES) {
      fr.reason = `file is ${size} bytes (> ${MAX_FILE_BYTES}); reported, not rewritten`;
      continue;
    }
    const oldRaw = await readFile(abs, "utf-8");
    let proposed: string;
    try {
      proposed = await claudePrompt(
        rewritePrompt(rel, oldRaw, item, observations, owner),
        model,
        240_000,
      );
    } catch (e) {
      fr.status = "error";
      fr.reason = (e as Error).message;
      continue;
    }
    const guarded = applyGuards(oldRaw, proposed, date);
    if (!guarded.ok) {
      fr.status = guarded.reason === "no change" ? "no-change" : "rejected";
      fr.reason = guarded.reason;
      continue;
    }
    fr.diff = await unifiedDiff(oldRaw, guarded.content, rel);
    if (opts.dryRun) {
      fr.status = "applied";
      fr.reason = "dry run — not written";
      continue;
    }
    await writeFile(abs, guarded.content);
    fr.status = "applied";
    fr.reason = item.reason;
  }

  if (!opts.only) {
    result.results.push(...(await bookSweep(recent, date, model, !!opts.dryRun)));
    result.results.push(...(await mediaSweep(recent, date, model, !!opts.dryRun)));
  }

  if (!opts.only) {
    result.nudgeSweep = await sweepOverdueNudges({
      entries,
      todayStr: date,
      model,
      dryRun: !!opts.dryRun,
    });
  }

  if (!opts.dryRun) result.logPath = await writeLog(result);
  return result;
}

async function unifiedDiff(a: string, b: string, label: string): Promise<string> {
  const dir = join(config.vaultPath, ".git", "reconcile-tmp");
  await mkdir(dir, { recursive: true });
  const pa = join(dir, "a.md");
  const pb = join(dir, "b.md");
  await writeFile(pa, a);
  await writeFile(pb, b);
  try {
    await execFileP("diff", [
      "-u",
      "--label",
      `a/${label}`,
      "--label",
      `b/${label}`,
      pa,
      pb,
    ]);
    return "";
  } catch (e: any) {
    // diff exits 1 when files differ — that is the normal success path
    const out: string = e.stdout ?? "";
    const lines = out.split("\n");
    return lines.length > 120
      ? lines.slice(0, 120).join("\n") + "\n... (truncated)"
      : out;
  }
}

async function writeLog(r: ReconcileResult): Promise<string> {
  const dir = join(config.vaultPath, RECONCILE_DIR_REL);
  await mkdir(dir, { recursive: true });
  const path = join(dir, `${r.date}.md`);
  const applied = r.results.filter((x) => x.status === "applied");
  const others = r.results.filter((x) => x.status !== "applied");
  const summary = applied.length
    ? applied.map((x) => `- **${x.file}** — ${x.reason}`).join("\n")
    : "- (no files changed)";
  const nudgeLines: string[] = [];
  if (r.nudgeSweep) {
    const { autoClosed, pastDueOpen } = r.nudgeSweep;
    if (autoClosed.length) {
      nudgeLines.push("## Nudges auto-closed");
      nudgeLines.push(...autoClosed.map((i) => `- **${i.nudge.goal}** — ${i.verdict.resolution}`));
      nudgeLines.push("");
    }
    if (pastDueOpen.length) {
      nudgeLines.push("## Nudges past-due (not enough evidence)");
      nudgeLines.push(...pastDueOpen.map((n) => `- **${n.goal}** (due ${n.due})`));
      nudgeLines.push("");
    }
  }
  const body = [
    `# Vault reconcile — ${r.date}`,
    "",
    `${r.entries} observation(s) over ${r.days} day(s); ${r.triage.length} file(s) triaged; ${applied.length} applied.`,
    "",
    "## Changed",
    summary,
    "",
    ...(others.length
      ? [
          "## Not changed",
          ...others.map((x) => `- ${x.file} — ${x.status}: ${x.reason}`),
          "",
        ]
      : []),
    ...nudgeLines,
    ...applied.flatMap((x) => [
      `## ${x.file}`,
      x.facts.length ? x.facts.map((f) => `- ${f}`).join("\n") : "",
      "```diff",
      x.diff ?? "",
      "```",
      "",
    ]),
  ].join("\n");
  const fm = {
    type: "ai-reconcile-log",
    date: r.date,
    tags: ["ai", "reconcile", "kb-system"],
    applied: applied.map((x) => x.file),
  };
  await writeFile(path, matter.stringify(`\n${body}`, fm));
  return path;
}

/**
 * One-liner-per-file summary of the most recent reconcile log.
 * Returns null when no recent log exists (used by the morning report).
 */
export async function latestReconcileSummary(
  maxAgeHours = 30,
): Promise<string | null> {
  const dir = join(config.vaultPath, RECONCILE_DIR_REL);
  let names: string[];
  try {
    names = (await readdir(dir))
      .filter((n) => /^\d{4}-\d{2}-\d{2}\.md$/.test(n))
      .sort();
  } catch {
    return null;
  }
  if (!names.length) return null;
  const latest = join(dir, names[names.length - 1]);
  const s = await stat(latest);
  if (Date.now() - s.mtimeMs > maxAgeHours * 3_600_000) return null;
  const { content } = matter(await readFile(latest, "utf-8"));
  const m = content.match(/## Changed\n([\s\S]*?)(?:\n## |\n*$)/);
  return m ? m[1].trim() : null;
}
